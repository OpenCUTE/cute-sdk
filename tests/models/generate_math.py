#!/usr/bin/env python3
"""Keep LMUL=1 stage math generated from the SDK's canonical polynomials."""
import argparse
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parents[2]/'cutelib/primitive/include'
s=(root/'cute_vec_math.h').read_text().replace('CUTE_VEC_MATH_H','CUTE_MODEL_MATH_H').replace('cute_fast_sqrt','cute_model_fast_sqrt').replace('cute_vec_','cute_model_vec_').replace('32m4','32m1').replace('vbool8_t','vbool32_t').replace('_b8','_b32')
s='/* Generated by tests/models/generate_math.py from cute_vec_math.h.\n * LMUL=1 keeps stage vectors in registers without hidden spill workspace. */\n'+s
out=root/'cute_model_math.h'
if a.check:
    if out.read_text()!=s:raise SystemExit('stale cute_model_math.h; run tests/models/generate_math.py')
else:out.write_text(s)
